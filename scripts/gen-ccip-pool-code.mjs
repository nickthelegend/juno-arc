// Regenerates lib/juno/ccip-pool-code.ts from Chainlink's published BurnMintTokenPool 2.0.0
// creation code (npm @chainlink/contracts-ccip 2.0.0, installed under contracts/), and checks its
// keccak256 against the hash JunoCrossChain was deployed with.
//   node scripts/gen-ccip-pool-code.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const BIN = "contracts/node_modules/@chainlink/contracts-ccip/bytecode/v2_0_0/burn_mint_token_pool.bin";
const EXPECTED = "0xdb3e7b4a67fbe75c634f0b65d08717c3c77fd5e7e081f75727edd355a9ceec03";

let hex = readFileSync(BIN, "utf8").trim();
if (!hex.startsWith("0x")) hex = `0x${hex}`;
const hash = keccak256(hex);
if (hash !== EXPECTED) {
  console.error(`hash mismatch: ${hash} != ${EXPECTED}`);
  process.exit(1);
}
writeFileSync(
  "lib/juno/ccip-pool-code.ts",
  `// Generated by scripts/gen-ccip-pool-code.mjs — do not edit.
// Chainlink's published BurnMintTokenPool 2.0.0 creation code (npm @chainlink/contracts-ccip 2.0.0,
// bytecode/v2_0_0/burn_mint_token_pool.bin). JunoCrossChain.enable only accepts init code with this hash.

export const CCIP_POOL_INIT_CODE_HASH = "${hash}" as const;

export const CCIP_POOL_INIT_CODE = "${hex}" as const;
`,
);
console.log(`lib/juno/ccip-pool-code.ts written (${(hex.length - 2) / 2} bytes, keccak ${hash})`);
